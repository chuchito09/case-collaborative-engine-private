    private String generarApplicationYml(DiagramaUml diagrama) {
        String dbName = "case_" + (diagrama.getProyecto() != null ? sanitizeIdentifier(diagrama.getProyecto().getNombre()) : "app_db");
        return """
            spring:
              application:
                name: generated-backend-app
              datasource:
                url: ${SPRING_DATASOURCE_URL:jdbc:postgresql://localhost:5432/%s}
                username: ${SPRING_DATASOURCE_USERNAME:postgres}
                password: ${SPRING_DATASOURCE_PASSWORD:postgres}
                driver-class-name: org.postgresql.Driver
              jpa:
                hibernate:
                  ddl-auto: update
                show-sql: true
                properties:
                  hibernate:
                    format_sql: true
            server:
              port: ${PORT:8081}
            """.formatted(dbName);
    }

