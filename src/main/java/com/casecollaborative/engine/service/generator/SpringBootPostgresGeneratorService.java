    private String normalizeJavaType(String rawType) {
        if (rawType == null || rawType.isBlank()) return "String";
        String t = rawType.trim().toLowerCase();

        if (t.equals("string") || t.contains("varchar") || t.contains("char") || t.contains("text")) return "String";
        if (t.equals("int") || t.equals("integer") || t.contains("entero") || t.equals("smallint")) return "Integer";
        if (t.equals("long") || t.equals("bigint") || t.equals("id")) return "Long";
        if (t.equals("double") || t.equals("float") || t.equals("real")) return "Double";
        if (t.contains("bigdecimal") || t.contains("decimal") || t.contains("numeric") || t.contains("money") || t.contains("precio") || t.contains("monto")) return "BigDecimal";
        if (t.equals("boolean") || t.equals("bool")) return "Boolean";
        if (t.equals("localdate") || t.equals("date") || t.contains("fecha") && !t.contains("hora")) return "LocalDate";
        if (t.equals("localdatetime") || t.equals("datetime") || t.equals("timestamp") || t.contains("fechahora")) return "LocalDateTime";
        if (t.equals("localtime") || t.equals("time") || t.contains("hora")) return "LocalTime";
        if (t.equals("uuid") || t.equals("guid")) return "UUID";
        if (t.equals("byte[]") || t.equals("blob") || t.equals("bytes")) return "byte[]";

        return capitalize(rawType.replaceAll("[^A-Za-z0-9_]", ""));
    }

    private String mapJavaTypeToSql(String javaType) {
        if (javaType == null) return "VARCHAR(255)";
        return switch (javaType) {
            case "String" -> "VARCHAR(255)";
            case "Integer" -> "INT";
            case "Long" -> "BIGINT";
            case "Double" -> "DOUBLE PRECISION";
            case "BigDecimal" -> "NUMERIC(19, 4)";
            case "Boolean" -> "BOOLEAN";
            case "LocalDate" -> "DATE";
            case "LocalDateTime" -> "TIMESTAMP WITHOUT TIME ZONE";
            case "LocalTime" -> "TIME WITHOUT TIME ZONE";
            case "UUID" -> "UUID";
            case "byte[]" -> "BYTEA";
            default -> "VARCHAR(255)";
        };
    }

    private Set<String> collectTypeImports(List<Atributo> atributos) {
        Set<String> imports = new TreeSet<>();
        if (atributos == null) return imports;

        for (Atributo a : atributos) {
            String javaType = normalizeJavaType(a.getTipoDato());
            switch (javaType) {
                case "LocalDate" -> imports.add("import java.time.LocalDate;");
                case "LocalDateTime" -> imports.add("import java.time.LocalDateTime;");
                case "LocalTime" -> imports.add("import java.time.LocalTime;");
                case "BigDecimal" -> imports.add("import java.math.BigDecimal;");
                case "UUID" -> imports.add("import java.util.UUID;");
            }
        }
        return imports;
    }

    private String resolvePkType(List<Atributo> atributos) {
        if (atributos != null) {
            for (Atributo a : atributos) {
                if (Boolean.TRUE.equals(a.getEsPk())) {
                    return normalizeJavaType(a.getTipoDato());
                }
            }
        }
        return "Long";
    }

    private String resolvePkGetterName(List<Atributo> atributos) {
        if (atributos != null) {
            for (Atributo a : atributos) {
                if (Boolean.TRUE.equals(a.getEsPk())) {
                    return sanitizeCamelCase(a.getNombre());
                }
            }
        }
        return "id";
    }

    private String sanitizeIdentifier(String raw) {
        if (raw == null || raw.isBlank()) return "tabla";
        return raw.replaceAll("[^A-Za-z0-9_]", "_").toLowerCase();
    }

    private String sanitizeCamelCase(String raw) {
        if (raw == null || raw.isBlank()) return "campo";
        String clean = raw.replaceAll("[^A-Za-z0-9_]", "");
        if (clean.isEmpty()) return "campo";
        return clean.substring(0, 1).toLowerCase() + clean.substring(1);
    }

    private String capitalize(String str) {
        if (str == null || str.isEmpty()) return str;
        return str.substring(0, 1).toUpperCase() + str.substring(1);
    }
