    private String generarEntity(String basePackage, Clase clase, List<Atributo> atributos, List<RelacionClase> relaciones) {
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".entity;\n\n");
        sb.append("import jakarta.persistence.*;\n");
        sb.append("import lombok.*;\n");

        Set<String> typeImports = collectTypeImports(atributos);
        for (String imp : typeImports) {
            sb.append(imp).append("\n");
        }

        boolean hasManyToMany = relaciones.stream().anyMatch(r -> !"HERENCIA".equalsIgnoreCase(r.getTipoRelacion()) && !"CLASE_ASOCIACION".equalsIgnoreCase(r.getTipoRelacion()) && isMany(r.getCardinalidadOrigen()) && isMany(r.getCardinalidadDestino()));
        if (hasManyToMany) {
            sb.append("import java.util.List;\n");
            sb.append("import java.util.ArrayList;\n");
        }
        sb.append("\n");

        sb.append("@Entity\n");
        sb.append("@Table(name = \"").append(sanitizeIdentifier(clase.getNombre())).append("\")\n");
        sb.append("@Getter\n@Setter\n@NoArgsConstructor\n@AllArgsConstructor\n@Builder\n");

        boolean isSuperClass = relaciones.stream().anyMatch(r -> "HERENCIA".equalsIgnoreCase(r.getTipoRelacion()) && r.getClaseDestino().getId().equals(clase.getId()));
        if (isSuperClass) {
            sb.append("@Inheritance(strategy = InheritanceType.JOINED)\n");
        }

        sb.append("public class ").append(clase.getNombre());

        boolean isSubClass = relaciones.stream().anyMatch(r -> "HERENCIA".equalsIgnoreCase(r.getTipoRelacion()) && r.getClaseOrigen().getId().equals(clase.getId()));
        if (isSubClass) {
            RelacionClase parentRel = relaciones.stream().filter(r -> "HERENCIA".equalsIgnoreCase(r.getTipoRelacion()) && r.getClaseOrigen().getId().equals(clase.getId())).findFirst().get();
            sb.append(" extends ").append(parentRel.getClaseDestino().getNombre());
        }
        sb.append(" {\n\n");

        boolean hasExplicitPk = atributos.stream().anyMatch(a -> Boolean.TRUE.equals(a.getEsPk()));
        if (!hasExplicitPk && !isSubClass) {
            sb.append("    @Id\n");
            sb.append("    @GeneratedValue(strategy = GenerationType.IDENTITY)\n");
            sb.append("    private Long id;\n\n");
        }

        for (Atributo a : atributos) {
            String fieldName = sanitizeCamelCase(a.getNombre());
            String javaType = normalizeJavaType(a.getTipoDato());

            if (Boolean.TRUE.equals(a.getEsPk())) {
                sb.append("    @Id\n");
                if ("Long".equals(javaType) || "Integer".equals(javaType)) {
                    sb.append("    @GeneratedValue(strategy = GenerationType.IDENTITY)\n");
                }
            }
            sb.append("    @Column(name = \"").append(sanitizeIdentifier(a.getNombre())).append("\")\n");
            sb.append("    private ").append(javaType).append(" ").append(fieldName).append(";\n\n");
        }

        List<Clase> assocPeers = getAssociationPeers(clase, relaciones);
        if (!assocPeers.isEmpty()) {
            for (Clase peer : assocPeers) {
                String targetClass = peer.getNombre();
                String targetField = sanitizeCamelCase(targetClass);
                sb.append("    @ManyToOne(fetch = FetchType.LAZY)\n");
                sb.append("    @JoinColumn(name = \"").append(sanitizeIdentifier(targetClass)).append("_id\")\n");
                sb.append("    private ").append(targetClass).append(" ").append(targetField).append(";\n\n");
            }
        }

        for (RelacionClase rel : relaciones) {
            if ("HERENCIA".equalsIgnoreCase(rel.getTipoRelacion()) || "CLASE_ASOCIACION".equalsIgnoreCase(rel.getTipoRelacion())) continue;

            if (isMany(rel.getCardinalidadOrigen()) && isMany(rel.getCardinalidadDestino())) {
                boolean hasAssocClass = relaciones.stream().anyMatch(r ->
                    "CLASE_ASOCIACION".equalsIgnoreCase(r.getTipoRelacion()) &&
                    (r.getClaseOrigen().getId().equals(rel.getClaseOrigen().getId()) || r.getClaseOrigen().getId().equals(rel.getClaseDestino().getId()) ||
                     r.getClaseDestino().getId().equals(rel.getClaseOrigen().getId()) || r.getClaseDestino().getId().equals(rel.getClaseDestino().getId()))
                );

                if (!hasAssocClass && rel.getClaseOrigen().getId().equals(clase.getId())) {
                    String targetClass = rel.getClaseDestino().getNombre();
                    String targetField = sanitizeCamelCase(targetClass) + "List";
                    String joinTable = sanitizeIdentifier(clase.getNombre()) + "_" + sanitizeIdentifier(targetClass);

                    sb.append("    @ManyToMany\n");
                    sb.append("    @JoinTable(\n");
                    sb.append("        name = \"").append(joinTable).append("\",\n");
                    sb.append("        joinColumns = @JoinColumn(name = \"").append(sanitizeIdentifier(clase.getNombre())).append("_id\"),\n");
                    sb.append("        inverseJoinColumns = @JoinColumn(name = \"").append(sanitizeIdentifier(targetClass)).append("_id\")\n");
                    sb.append("    )\n");
                    sb.append("    @Builder.Default\n");
                    sb.append("    private List<").append(targetClass).append("> ").append(targetField).append(" = new ArrayList<>();\n\n");
                }
            } else if (isOne(rel.getCardinalidadDestino()) && isMany(rel.getCardinalidadOrigen())) {
                if (rel.getClaseOrigen().getId().equals(clase.getId())) {
                    String targetClass = rel.getClaseDestino().getNombre();
                    String targetField = sanitizeCamelCase(targetClass);
                    sb.append("    @ManyToOne(fetch = FetchType.LAZY)\n");
                    sb.append("    @JoinColumn(name = \"").append(sanitizeIdentifier(targetClass)).append("_id\")\n");
                    sb.append("    private ").append(targetClass).append(" ").append(targetField).append(";\n\n");
                }
            } else if (isOne(rel.getCardinalidadOrigen()) && isMany(rel.getCardinalidadDestino())) {
                if (rel.getClaseDestino().getId().equals(clase.getId())) {
                    String targetClass = rel.getClaseOrigen().getNombre();
                    String targetField = sanitizeCamelCase(targetClass);
                    sb.append("    @ManyToOne(fetch = FetchType.LAZY)\n");
                    sb.append("    @JoinColumn(name = \"").append(sanitizeIdentifier(targetClass)).append("_id\")\n");
                    sb.append("    private ").append(targetClass).append(" ").append(targetField).append(";\n\n");
                }
            }
        }

        sb.append("}\n");
        return sb.toString();
    }

    private String generarRequestDto(String basePackage, Clase clase, List<Atributo> atributos) {
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".dto;\n\n");

        Set<String> typeImports = collectTypeImports(atributos);
        for (String imp : typeImports) {
            sb.append(imp).append("\n");
        }
        sb.append("\n");

        sb.append("public record ").append(clase.getNombre()).append("RequestDTO(\n");

        List<Atributo> nonPkAttributes = atributos.stream()
                .filter(a -> !Boolean.TRUE.equals(a.getEsPk()) && !a.getNombre().equalsIgnoreCase("id"))
                .collect(Collectors.toList());

        List<Atributo> targetList = nonPkAttributes.isEmpty() ? atributos : nonPkAttributes;

        for (int i = 0; i < targetList.size(); i++) {
            Atributo a = targetList.get(i);
            String javaType = normalizeJavaType(a.getTipoDato());
            String fieldName = sanitizeCamelCase(a.getNombre());

            sb.append("    ").append(javaType).append(" ").append(fieldName);
            if (i < targetList.size() - 1) sb.append(",\n");
        }

        sb.append("\n) {}\n");
        return sb.toString();
    }

    private String generarResponseDto(String basePackage, Clase clase, List<Atributo> atributos) {
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".dto;\n\n");

        Set<String> typeImports = collectTypeImports(atributos);
        for (String imp : typeImports) {
            sb.append(imp).append("\n");
        }
        sb.append("\n");

        sb.append("public record ").append(clase.getNombre()).append("ResponseDTO(\n");

        boolean hasExplicitPk = atributos.stream().anyMatch(a -> Boolean.TRUE.equals(a.getEsPk()));
        boolean first = true;

        if (!hasExplicitPk) {
            sb.append("    Long id");
            first = false;
        }

        for (Atributo a : atributos) {
            if (!first) sb.append(",\n");
            String javaType = normalizeJavaType(a.getTipoDato());
            String fieldName = sanitizeCamelCase(a.getNombre());
            sb.append("    ").append(javaType).append(" ").append(fieldName);
            first = false;
        }

        sb.append("\n) {}\n");
        return sb.toString();
    }

    private String generarRepository(String basePackage, Clase clase, List<Atributo> atributos) {
        String pkType = resolvePkType(atributos);
        Set<String> typeImports = collectTypeImports(atributos);

        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".repository;\n\n");
        sb.append("import ").append(basePackage).append(".entity.").append(clase.getNombre()).append(";\n");
        sb.append("import org.springframework.data.jpa.repository.JpaRepository;\n");
        sb.append("import org.springframework.stereotype.Repository;\n");

        for (String imp : typeImports) {
            if (imp.contains(pkType)) {
                sb.append(imp).append("\n");
            }
        }
        sb.append("\n");

        sb.append("@Repository\n");
        sb.append("public interface ").append(clase.getNombre()).append("Repository extends JpaRepository<")
                .append(clase.getNombre()).append(", ").append(pkType).append("> {\n");
        sb.append("}\n");

        return sb.toString();
    }

    private String generarService(String basePackage, Clase clase, List<Atributo> atributos) {
        String className = clase.getNombre();
        String pkType = resolvePkType(atributos);
        Set<String> typeImports = collectTypeImports(atributos);

        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".service;\n\n");
        sb.append("import ").append(basePackage).append(".dto.").append(className).append("RequestDTO;\n");
        sb.append("import ").append(basePackage).append(".dto.").append(className).append("ResponseDTO;\n");
        sb.append("import ").append(basePackage).append(".entity.").append(className).append(";\n");
        sb.append("import ").append(basePackage).append(".repository.").append(className).append("Repository;\n");
        sb.append("import org.springframework.stereotype.Service;\n");
        sb.append("import org.springframework.transaction.annotation.Transactional;\n\n");
        sb.append("import java.util.List;\n");
        sb.append("import java.util.Optional;\n");
        sb.append("import java.util.stream.Collectors;\n");

        for (String imp : typeImports) {
            sb.append(imp).append("\n");
        }
        sb.append("\n");

        sb.append("@Service\n");
        sb.append("@Transactional\n");
        sb.append("public class ").append(className).append("Service {\n\n");
        sb.append("    private final ").append(className).append("Repository repository;\n\n");
        sb.append("    public ").append(className).append("Service(").append(className).append("Repository repository) {\n");
        sb.append("        this.repository = repository;\n");
        sb.append("    }\n\n");

        // 1. GET all
        sb.append("    @Transactional(readOnly = true)\n");
        sb.append("    public List<").append(className).append("ResponseDTO> findAll() {\n");
        sb.append("        return repository.findAll().stream()\n");
        sb.append("                .map(this::toResponseDTO)\n");
        sb.append("                .collect(Collectors.toList());\n");
        sb.append("    }\n\n");

        // 2. GET by ID
        sb.append("    @Transactional(readOnly = true)\n");
        sb.append("    public Optional<").append(className).append("ResponseDTO> findById(").append(pkType).append(" id) {\n");
        sb.append("        return repository.findById(id).map(this::toResponseDTO);\n");
        sb.append("    }\n\n");

        // 3. POST create
        sb.append("    public ").append(className).append("ResponseDTO create(").append(className).append("RequestDTO dto) {\n");
        sb.append("        ").append(className).append(" entity = toEntity(dto);\n");
        sb.append("        ").append(className).append(" saved = repository.save(entity);\n");
        sb.append("        return toResponseDTO(saved);\n");
        sb.append("    }\n\n");

        // 4. PUT update
        sb.append("    public Optional<").append(className).append("ResponseDTO> update(").append(pkType).append(" id, ").append(className).append("RequestDTO dto) {\n");
        sb.append("        return repository.findById(id).map(existing -> {\n");
        sb.append("            updateEntityFromDTO(existing, dto);\n");
        sb.append("            ").append(className).append(" updated = repository.save(existing);\n");
        sb.append("            return toResponseDTO(updated);\n");
        sb.append("        });\n");
        sb.append("    }\n\n");

        // 5. DELETE
        sb.append("    public boolean deleteById(").append(pkType).append(" id) {\n");
        sb.append("        if (repository.existsById(id)) {\n");
        sb.append("            repository.deleteById(id);\n");
        sb.append("            return true;\n");
        sb.append("        }\n");
        sb.append("        return false;\n");
        sb.append("    }\n\n");

        // Mapper toResponseDTO
        sb.append("    private ").append(className).append("ResponseDTO toResponseDTO(").append(className).append(" entity) {\n");
        sb.append("        return new ").append(className).append("ResponseDTO(\n");

        boolean hasExplicitPk = atributos.stream().anyMatch(a -> Boolean.TRUE.equals(a.getEsPk()));
        boolean first = true;
        if (!hasExplicitPk) {
            sb.append("            entity.getId()");
            first = false;
        }

        for (Atributo a : atributos) {
            if (!first) sb.append(",\n");
            String getter = "get" + capitalize(sanitizeCamelCase(a.getNombre())) + "()";
            sb.append("            entity.").append(getter);
            first = false;
        }
        sb.append("\n        );\n");
        sb.append("    }\n\n");

        // Mapper toEntity
        sb.append("    private ").append(className).append(" toEntity(").append(className).append("RequestDTO dto) {\n");
        sb.append("        ").append(className).append(" entity = new ").append(className).append("();\n");
        sb.append("        updateEntityFromDTO(entity, dto);\n");
        sb.append("        return entity;\n");
        sb.append("    }\n\n");

        // Mapper updateEntityFromDTO
        sb.append("    private void updateEntityFromDTO(").append(className).append(" entity, ").append(className).append("RequestDTO dto) {\n");
        for (Atributo a : atributos) {
            if (Boolean.TRUE.equals(a.getEsPk()) || a.getNombre().equalsIgnoreCase("id")) {
                continue;
            }
            String fieldName = sanitizeCamelCase(a.getNombre());
            String setter = "set" + capitalize(fieldName);
            sb.append("        entity.").append(setter).append("(dto.").append(fieldName).append("());\n");
        }
        sb.append("    }\n");

        sb.append("}\n");
        return sb.toString();
    }

    private String generarController(String basePackage, Clase clase, List<Atributo> atributos) {
        String className = clase.getNombre();
        String pkType = resolvePkType(atributos);
        String pkGetter = resolvePkGetterName(atributos);
        String endpointPath = sanitizeIdentifier(className).toLowerCase() + "s";
        Set<String> typeImports = collectTypeImports(atributos);

        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(basePackage).append(".controller;\n\n");
        sb.append("import ").append(basePackage).append(".dto.").append(className).append("RequestDTO;\n");
        sb.append("import ").append(basePackage).append(".dto.").append(className).append("ResponseDTO;\n");
        sb.append("import ").append(basePackage).append(".service.").append(className).append("Service;\n");
        sb.append("import jakarta.validation.Valid;\n");
        sb.append("import org.springframework.http.HttpStatus;\n");
        sb.append("import org.springframework.http.ResponseEntity;\n");
        sb.append("import org.springframework.web.bind.annotation.*;\n\n");
        sb.append("import java.net.URI;\n");
        sb.append("import java.util.List;\n");

        for (String imp : typeImports) {
            if (imp.contains(pkType)) {
                sb.append(imp).append("\n");
            }
        }
        sb.append("\n");

        sb.append("@RestController\n");
        sb.append("@RequestMapping(\"/api/").append(endpointPath).append("\")\n");
        sb.append("@CrossOrigin(originPatterns = \"*\")\n");
        sb.append("public class ").append(className).append("Controller {\n\n");
        sb.append("    private final ").append(className).append("Service service;\n\n");
        sb.append("    public ").append(className).append("Controller(").append(className).append("Service service) {\n");
        sb.append("        this.service = service;\n");
        sb.append("    }\n\n");

        // 1. GET ALL
        sb.append("    @GetMapping\n");
        sb.append("    public ResponseEntity<List<").append(className).append("ResponseDTO>> findAll() {\n");
        sb.append("        return ResponseEntity.ok(service.findAll());\n");
        sb.append("    }\n\n");

        // 2. GET BY ID
        sb.append("    @GetMapping(\"/{id}\")\n");
        sb.append("    public ResponseEntity<").append(className).append("ResponseDTO> findById(@PathVariable ").append(pkType).append(" id) {\n");
        sb.append("        return service.findById(id)\n");
        sb.append("                .map(ResponseEntity::ok)\n");
        sb.append("                .orElseGet(() -> ResponseEntity.notFound().build());\n");
        sb.append("    }\n\n");

        // 3. POST CREATE
        sb.append("    @PostMapping\n");
        sb.append("    public ResponseEntity<").append(className).append("ResponseDTO> create(@Valid @RequestBody ").append(className).append("RequestDTO dto) {\n");
        sb.append("        ").append(className).append("ResponseDTO created = service.create(dto);\n");
        sb.append("        URI location = URI.create(\"/api/").append(endpointPath).append("/\" + created.").append(pkGetter).append("());\n");
        sb.append("        return ResponseEntity.status(HttpStatus.CREATED).location(location).body(created);\n");
        sb.append("    }\n\n");

        // 4. PUT UPDATE
        sb.append("    @PutMapping(\"/{id}\")\n");
        sb.append("    public ResponseEntity<").append(className).append("ResponseDTO> update(@PathVariable ").append(pkType).append(" id, @Valid @RequestBody ").append(className).append("RequestDTO dto) {\n");
        sb.append("        return service.update(id, dto)\n");
        sb.append("                .map(ResponseEntity::ok)\n");
        sb.append("                .orElseGet(() -> ResponseEntity.notFound().build());\n");
        sb.append("    }\n\n");

        // 5. DELETE
        sb.append("    @DeleteMapping(\"/{id}\")\n");
        sb.append("    public ResponseEntity<Void> deleteById(@PathVariable ").append(pkType).append(" id) {\n");
        sb.append("        if (service.deleteById(id)) {\n");
        sb.append("            return ResponseEntity.noContent().build();\n");
        sb.append("        }\n");
        sb.append("        return ResponseEntity.notFound().build();\n");
        sb.append("    }\n");

        sb.append("}\n");
        return sb.toString();
    }

